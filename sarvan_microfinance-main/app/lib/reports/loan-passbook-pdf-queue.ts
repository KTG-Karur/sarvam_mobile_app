import { jsPDF } from "jspdf";
import { format } from "date-fns";
import { prisma } from "@/app/lib/prisma";
import { loanService } from "@/app/lib/services/loan.service";
import { drawLoanPassbookReport, type PassbookInstallmentRow } from "@/app/lib/reports/loan-passbook-pdf";
import { drawPdfReportHeaderServer } from "@/app/lib/reports/pdf-report-header-server";
import { ensureReportFontServer } from "@/app/lib/reports/pdf-fonts-server";
import type { BuildReportFileContext } from "@/app/lib/reports/generic-file-builder";
import { formatReportAmountPlain } from "@/app/lib/utils/format-amount";

/**
 * Request Report / Request Queue PDF renderer for "loan-passbook" — this
 * targets the PLAIN tabular passbook export
 * (components/reports/PassbookFormPage.tsx's handleExportPDF), NOT the
 * bespoke Tamil-language 2-page document generated by
 * POST /api/generate-passbook (LoanPassbookDialog) — that feature is a
 * separate code path never wired to reportSlug/the Request Queue at all,
 * so there is nothing on the Queue side to reconcile it against.
 *
 * report-registry.ts's own fetchLoanPassbook computes a DIFFERENT dataset
 * than Direct (due-vs-paid ledger view, vs Direct's principal/interest
 * amortization schedule from GET /api/loans/[loanId]/passbook) — per the
 * project's data rule ("fix the architecture so both use the same
 * authoritative data preparation"), this queue builder bypasses that
 * divergent registry fetch and replicates the live route's own
 * installment computation directly (loan.schedules, or
 * loanService.calculateScheduleFromFirstDueDate() for the pre-disbursement
 * preview case), so Queue and Direct produce identical numbers. The
 * route's client-photo resolution is intentionally not replicated — the
 * flat PDF table never renders it.
 */
export async function buildLoanPassbookQueuePdf(ctx: BuildReportFileContext): Promise<Buffer> {
  const loanId = ctx.filters?.loanId;
  if (!loanId) {
    throw new Error("filters.loanId is required for the Loan Passbook report");
  }

  const loan = await prisma.loan.findUnique({
    where: { id: loanId },
    include: {
      client: { select: { firstName: true, lastName: true } },
      loanProduct: {
        select: {
          numberOfDues: true, interestAmount: true, interestMethod: true,
          documentCharges: true, insuranceFees: true, advanceSavingsAmount: true,
          scheduleTemplates: { orderBy: { installmentNo: "asc" }, select: { installmentNo: true, principalAmount: true, interestAmount: true } },
        },
      },
      schedules: { orderBy: { installmentNo: "asc" }, select: { installmentNo: true, dueDate: true, principalDue: true, interestDue: true } },
    },
  });
  if (!loan) throw new Error("Loan not found");
  if (ctx.branchIds && (!loan.branchId || !ctx.branchIds.includes(loan.branchId))) {
    throw new Error("Unauthorized loan access");
  }

  const effectiveFirstDueDate = loan.firstDueDate ? format(new Date(loan.firstDueDate), "yyyy-MM-dd") : null;

  let scheduleRows: { installmentNo: number; dueDate: Date; principalDue: unknown; interestDue: unknown }[] = loan.schedules;
  if (loan.schedules.length === 0 && effectiveFirstDueDate) {
    const computed = loanService.calculateScheduleFromFirstDueDate(
      { amount: loan.amount, interestRate: loan.interestRate, tenureMonths: loan.tenureMonths, frequency: loan.frequency },
      loan.loanProduct
        ? {
            numberOfDues: loan.loanProduct.numberOfDues,
            interestAmount: loan.loanProduct.interestAmount,
            interestMethod: loan.loanProduct.interestMethod,
            documentCharges: loan.loanProduct.documentCharges,
            insuranceFees: loan.loanProduct.insuranceFees,
            advanceSavingsAmount: loan.loanProduct.advanceSavingsAmount,
          }
        : null,
      new Date(effectiveFirstDueDate),
      loan.loanProduct?.scheduleTemplates?.length ? loan.loanProduct.scheduleTemplates : undefined
    );
    scheduleRows = computed.map((item) => ({ installmentNo: item.installmentNo, dueDate: item.dueDate, principalDue: item.principalDue, interestDue: item.interestDue }));
  }

  let runningBalance = Number(loan.amount);
  const installments: PassbookInstallmentRow[] = scheduleRows.map((s) => {
    const principal = Number(s.principalDue);
    const interest = Number(s.interestDue);
    runningBalance -= principal;
    return {
      no: s.installmentNo,
      date: format(new Date(s.dueDate), "dd/MM/yyyy"),
      principal: formatReportAmountPlain(principal),
      interest: formatReportAmountPlain(interest),
      balance: formatReportAmountPlain(Math.max(0, runningBalance)),
    };
  });

  const memberName = `${loan.client.firstName} ${loan.client.lastName ?? ""}`.trim();

  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const reportFont = ensureReportFontServer(doc);

  await drawLoanPassbookReport(doc, installments, { subtitle: `${memberName} — ${loan.loanNumber}` }, reportFont, drawPdfReportHeaderServer);

  return Buffer.from(doc.output("arraybuffer"));
}
