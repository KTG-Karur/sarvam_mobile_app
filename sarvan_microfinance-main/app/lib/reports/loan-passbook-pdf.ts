import type { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { drawPdfReportHeader } from "@/app/lib/reports/pdf-report-header";

/** Signature shared with the other migrated reports' PdfHeaderDrawer — lets a server caller
 * (no window/DOM) inject its own Node-safe logo/font loading in place of the browser-only
 * drawPdfReportHeader default. */
export type PdfHeaderDrawer = (
  doc: jsPDF,
  title: string,
  opts?: { subtitle?: string; fontFamily?: string }
) => Promise<number>;

export interface PassbookInstallmentRow {
  no: number;
  date: string;
  principal: string;
  interest: string;
  balance: string;
}

/**
 * Draws the (plain tabular) Loan Passbook export — trust header, then a
 * single flat A4-portrait table (no header grouping, no totals row) —
 * extracted verbatim from the Direct Download PDF logic in
 * components/reports/PassbookFormPage.tsx's handleExportPDF /
 * buildPassbookExportRows, so the exact same rendering can be reused by
 * the Request Report queue's PDF builder (via an injected Node-safe
 * `drawHeader`) without duplicating the table logic. `drawHeader` defaults
 * to the browser drawPdfReportHeader, so the existing Direct caller is
 * unaffected by this extraction.
 *
 * NOT the bespoke Tamil-language 2-page passbook document generated by
 * POST /api/generate-passbook (LoanPassbookDialog) — that feature is a
 * completely separate code path not wired to reportSlug/the Request Queue
 * at all, and is untouched by this migration.
 */
export async function drawLoanPassbookReport(
  doc: jsPDF,
  installments: PassbookInstallmentRow[],
  meta: { subtitle: string },
  reportFont: string,
  drawHeader: PdfHeaderDrawer = drawPdfReportHeader
): Promise<void> {
  const headers = ["No", "Due Date", "Principal", "Interest", "Balance"];
  const rows: (string | number)[][] = installments.map((inst) => [inst.no, inst.date, inst.principal, inst.interest, inst.balance]);

  const headerY = await drawHeader(doc, "LOAN PASSBOOK", {
    subtitle: meta.subtitle,
    fontFamily: reportFont,
  });

  autoTable(doc, {
    startY: headerY,
    head: [headers],
    body: rows,
    styles: { font: reportFont, fontSize: 8, cellPadding: 1.5 },
    headStyles: { font: reportFont },
  });
}
