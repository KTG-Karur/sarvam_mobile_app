/// Resolves a stored `fileUrl` (a bare, private-bucket object key for any
/// document uploaded through this app) to a signed, viewable URL before
/// rendering it — a raw `Image.network(key)` always fails ("Could not load
/// this document") since the bucket isn't public. Cached process-wide by
/// key so re-opening the same document, or the same [Obx] rebuilding, don't
/// re-request a fresh signed URL every time.
class _SignedImage extends StatefulWidget {
  const _SignedImage({
    required this.api,
    required this.rawUrlOrKey,
    this.errorWidget,
  });

  final EnrollmentApiService api;
  final String rawUrlOrKey;
  final Widget? errorWidget;

  static final Map<String, Future<String?>> _cache = {};

  @override
  State<_SignedImage> createState() => _SignedImageState();
}

class _SignedImageState extends State<_SignedImage> {
  late Future<String?> _future;

  @override
  void initState() {
    super.initState();
    _future = _SignedImage._cache.putIfAbsent(
      widget.rawUrlOrKey,
      () => widget.api.resolveFileUrl(widget.rawUrlOrKey),
    );
  }

  @override
  Widget build(BuildContext context) => FutureBuilder<String?>(
    future: _future,
    builder: (context, snapshot) {
      if (snapshot.connectionState != ConnectionState.done) {
        return const Center(child: CircularProgressIndicator(strokeWidth: 2));
      }
      final url = snapshot.data;
      if (url == null || url.isEmpty) {
        return widget.errorWidget ??
            const Icon(Icons.broken_image_outlined, color: Color(0xFFA9C9B7));
      }
      return Image.network(
        url,
        fit: BoxFit.cover,
        errorBuilder: (_, __, ___) =>
            widget.errorWidget ??
            const Icon(Icons.broken_image_outlined, color: Color(0xFFA9C9B7)),
        loadingBuilder: (context, child, progress) =>
            progress == null ? child : const Center(child: CircularProgressIndicator(strokeWidth: 2)),
      );
    },
  );
}

