  void _showScanIdModal(BuildContext context, String documentType, {required String owner}) {
    final isAadhaar = documentType.toLowerCase().contains('aadhaar');
    final title = isAadhaar ? 'Scan Aadhaar Card' : 'Scan PAN Card';
    final ctrl = TextEditingController();

    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14.r)),
        title: Row(
          children: [
            const Icon(Icons.qr_code_scanner_rounded, color: enrollmentGreen),
            SizedBox(width: 8.w),
            Expanded(
              child: Text(
                title,
                style: TextStyle(fontSize: 16.sp, fontWeight: FontWeight.w800, color: const Color(0xFF063B20)),
                overflow: TextOverflow.ellipsis,
              ),
            ),
          ],
        ),
        content: SingleChildScrollView(
          child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              isAadhaar
                  ? 'Enter or scan 12-digit Aadhaar Number:'
                  : 'Enter or scan 10-character PAN Card Number:',
              style: TextStyle(fontSize: 12.sp, color: Colors.grey[700]),
            ),
            SizedBox(height: 12.h),
            TextField(
              controller: ctrl,
              maxLength: isAadhaar ? 12 : 10,
              keyboardType: isAadhaar ? TextInputType.number : TextInputType.text,
              textCapitalization: TextCapitalization.characters,
              decoration: InputDecoration(
                hintText: isAadhaar ? '123456789012' : 'ABCDE1234F',
                border: const OutlineInputBorder(),
                prefixIcon: Icon(isAadhaar ? Icons.badge_outlined : Icons.credit_card_outlined),
              ),
            ),
          ],
        ),
      ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: const Text('Cancel'),
          ),
          ElevatedButton.icon(
            style: ElevatedButton.styleFrom(backgroundColor: enrollmentGreen, foregroundColor: Colors.white),
            icon: const Icon(Icons.check_rounded, size: 18),
            label: const Text('Auto-Fill Field'),
            onPressed: () {
              final val = ctrl.text.trim();
              if (val.isEmpty) {
                Get.snackbar('Input Required', 'Please enter a valid number.', backgroundColor: Colors.orange, colorText: Colors.white);
                return;
              }
              if (isAadhaar) {
                if (owner == 'client') {
                  controller.otherIdNoCtrl.text = val;
                } else {
                  controller.caOtherIdNoCtrl.text = val;
                }
              } else {
                if (owner == 'client') {
                  controller.pancardNoCtrl.text = val;
                } else {
                  controller.caPancardNoCtrl.text = val;
                }
              }
              Navigator.pop(ctx);
              Get.snackbar(
                'Auto-Filled',
                '${isAadhaar ? "Aadhaar Number" : "PAN Card Number"} updated successfully.',
                backgroundColor: enrollmentGreen,
                colorText: Colors.white,
              );
            },
          ),
        ],
      ),
    );
  }

  /// A single KYC document tile — image thumbnail (or a PDF/placeholder
  /// icon) with upload/view/delete actions, matching the web app's document
  /// card layout so an uploaded document can actually be seen/reviewed
  /// inline instead of only showing a checkmark.
  Widget _docCard(String documentType, String label, {required String owner}) => Obx(() {
    final state = controller.docState(documentType);
    final allowPdf = EnrollmentOptions.pdfEligibleDocumentTypes.contains(documentType);
    final isPdf = (state?.mimeType ?? '').toLowerCase().contains('pdf');
    final uploaded = state?.isUploaded == true;
    final uploading = state?.isUploading == true;

    return SizedBox(
      width: 104.w,
      child: Column(
        children: [
          Builder(
            builder: (ctx) => InkWell(
              borderRadius: BorderRadius.circular(8.r),
              onTap: uploading
                  ? null
                  : uploaded
                      ? () => _previewDocument(ctx, state!, label)
                      : () => _showUploadSourceSheet(ctx, documentType, label, owner: owner, allowPdf: allowPdf),
              child: Container(
                width: 104.w,
                height: 90.h,
                decoration: BoxDecoration(
                  color: const Color(0xFFF1F8F4),
                  borderRadius: BorderRadius.circular(8.r),
                  border: Border.all(color: const Color(0xFFCFE9DA)),
                ),
                clipBehavior: Clip.antiAlias,
                child: uploading
                    ? const Center(child: CircularProgressIndicator(strokeWidth: 2))
                    : !uploaded
                        ? Icon(Icons.image_outlined, size: 30.sp, color: const Color(0xFFA9C9B7))
                        : isPdf
                            ? Icon(Icons.picture_as_pdf_rounded, size: 30.sp, color: const Color(0xFFB91C1C))
                            : _SignedImage(
                                api: controller.api,
                                rawUrlOrKey: state!.fileUrl!,
                                errorWidget: Icon(Icons.broken_image_outlined, size: 28.sp, color: const Color(0xFFA9C9B7)),
                              ),
              ),
            ),
          ),
          SizedBox(height: 4.h),
          Text(
            label,
            textAlign: TextAlign.center,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
            style: TextStyle(fontSize: 10.sp, fontWeight: FontWeight.w600, color: const Color(0xFF164A2E)),
          ),
          SizedBox(height: 4.h),
          Row(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              Builder(
                builder: (ctx) => _cardIconButton(
                  icon: uploaded ? Icons.refresh_rounded : Icons.upload_rounded,
                  onTap: () => _showUploadSourceSheet(ctx, documentType, label, owner: owner, allowPdf: allowPdf),
                ),
              ),
              if (uploaded) ...[
                SizedBox(width: 4.w),
                Builder(
                  builder: (ctx) => _cardIconButton(
                    icon: Icons.visibility_outlined,
                    onTap: () => _previewDocument(ctx, state!, label),
                  ),
                ),
                SizedBox(width: 4.w),
                _cardIconButton(
                  icon: Icons.delete_outline_rounded,
                  color: const Color(0xFFB91C1C),
                  onTap: () => controller.removeDocument(documentType),
                ),
              ],
            ],
          ),
        ],
      ),
    );
  });

  Widget _cardIconButton({required IconData icon, required VoidCallback onTap, Color? color}) => InkWell(
    borderRadius: BorderRadius.circular(6.r),
    onTap: onTap,
    child: Padding(
      padding: EdgeInsets.all(3.w),
      child: Icon(icon, size: 15.sp, color: color ?? enrollmentGreen),
    ),
  );

  void _previewDocument(BuildContext context, EnrollmentDocState state, String label) {
    final isPdf = (state.mimeType ?? '').toLowerCase().contains('pdf');
    final url = state.fileUrl;
    if (url == null || url.isEmpty) return;
    if (isPdf) {
      Get.snackbar(
        label,
        'This is a PDF document — use "Replace" to re-upload if needed.',
        backgroundColor: const Color(0xFF334155),
        colorText: Colors.white,
      );
      return;
    }
    showDialog<void>(
      context: context,
      builder: (ctx) => Dialog(
        insetPadding: const EdgeInsets.all(16),
        backgroundColor: Colors.transparent,
        child: Stack(
          alignment: Alignment.topRight,
          children: [
            ClipRRect(
              borderRadius: BorderRadius.circular(12),
              child: SizedBox(
                width: 320,
                height: 320,
                child: InteractiveViewer(
                  child: _SignedImage(
                    api: controller.api,
                    rawUrlOrKey: url,
                    errorWidget: Container(
                      color: Colors.white,
                      padding: const EdgeInsets.all(24),
                      child: const Text('Could not load this document.'),
                    ),
                  ),
                ),
              ),
            ),
            IconButton(
              onPressed: () => Navigator.pop(ctx),
              icon: const CircleAvatar(
                backgroundColor: Colors.black54,
                child: Icon(Icons.close, color: Colors.white, size: 18),
              ),
            ),
          ],
        ),
      ),
    );
  }
